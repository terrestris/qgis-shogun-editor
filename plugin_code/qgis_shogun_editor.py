from .models.Application import Application
from .qgis_shogun_editor_dialog import QgisShogunEditorDialog
from .service.Application import ApplicationService
from .service.GraphQLClient import GraphQLClient
from .service.KeycloakAuth import KeycloakAuth
from .service.LayerService import LayerService


class QgisShogunEditor:
    """QGIS Plugin Implementation."""

    SETTINGS_GROUP = "QgisShogunEditor"
    KEY_KEYCLOAK_URL = "keycloakUrl"
    KEY_CLIENT_ID = "clientId"
    KEY_GRAPHQL_URL = "graphqlUrl"

    def __init__(self, iface):
        self.iface = iface
        self.plugin_dir = os.path.dirname(__file__)
        self.qgis_settings = QSettings()

        self.layer_service: LayerService = None
        self.app_service: ApplicationService = None
        self.graphql_client: GraphQLClient = None
        self.keycloak_auth: KeycloakAuth = None

        locale = QSettings().value('locale/userLocale')[0:2]
        locale_path = os.path.join(self.plugin_dir, 'i18n', f'qgis_shogun_editor{locale}.qm')
        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

        self.actions = []
        self.menu = self.tr('&Shogun QGIS Editor')
        self.first_start = True

    def tr(self, message):
        return QCoreApplication.translate('QgisShogunEditor', message)

    def add_action(
            self,
            icon_path,
            text,
            callback,
            enabled_flag=True,
            add_to_menu=True,
            add_to_toolbar=True,
            status_tip=None,
            whats_this=None,
            parent=None):
        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        if status_tip is not None:
            action.setStatusTip(status_tip)
        if whats_this is not None:
            action.setWhatsThis(whats_this)
        if add_to_toolbar:
            self.iface.addToolBarIcon(action)
        if add_to_menu:
            self.iface.addPluginToWebMenu(self.menu, action)

        self.actions.append(action)
        return action

    def initGui(self):
        icon_path = os.path.join(os.path.dirname(__file__), "shogun_logo.png")
        self.add_action(
            icon_path,
            text=self.tr('Shogun QGIS Editor'),
            callback=self.run,
            parent=self.iface.mainWindow())

    def unload(self):
        for action in self.actions:
            self.iface.removePluginWebMenu(self.tr('Shogun QGIS Editor'), action)
            self.iface.removeToolBarIcon(action)

    def run(self):
        if self.first_start:
            self.first_start = False
            self._setup_dialog()
        self.dlg.show()

    def _setup_dialog(self):
        self.dlg = QgisShogunEditorDialog()

        self.keycloak_auth = KeycloakAuth()
        self.keycloak_auth.login_successful.connect(self._on_login_success)
        self.keycloak_auth.login_failed.connect(self._on_login_failed)

        self._load_settings()
        self._connect_signals()
        self._setup_logo()

    def _load_settings(self):
        self.dlg.set_keycloak_url(
            self.qgis_settings.value(f"{self.SETTINGS_GROUP}/{self.KEY_KEYCLOAK_URL}",
                                      KeycloakAuth.DEFAULT_PROVIDER_URL))
        self.dlg.set_client_id(
            self.qgis_settings.value(f"{self.SETTINGS_GROUP}/{self.KEY_CLIENT_ID}",
                                      KeycloakAuth.DEFAULT_CLIENT_ID))
        self.dlg.set_graphql_url(
            self.qgis_settings.value(f"{self.SETTINGS_GROUP}/{self.KEY_GRAPHQL_URL}",
                                     "https://gdaw-intern2024.intranet.terrestris.de/gdawasser-boot/graphql"))

    def _save_settings(self):
        self.qgis_settings.setValue(f"{self.SETTINGS_GROUP}/{self.KEY_KEYCLOAK_URL}",
                                     self.dlg.get_keycloak_url())
        self.qgis_settings.setValue(f"{self.SETTINGS_GROUP}/{self.KEY_CLIENT_ID}",
                                     self.dlg.get_client_id())
        self.qgis_settings.setValue(f"{self.SETTINGS_GROUP}/{self.KEY_GRAPHQL_URL}",
                                     self.dlg.get_graphql_url())

    def _connect_signals(self):
        self.dlg.connect_login_button(self._handle_login)
        self.dlg.connect_load_button(self._handle_load)
        self.dlg.connect_cancel_button(self._handle_cancel)
        self.dlg.connect_table_double_click(self._handle_table_double_click)

    def _setup_logo(self):
        logo_path = os.path.join(os.path.dirname(__file__), "shogun_logo.png")
        if os.path.exists(logo_path):
            pixmap = QPixmap(logo_path)
            self.dlg.set_logo(pixmap)
            self.dlg.labelLogo.mousePressEvent = self._open_project_link
        else:
            QgsMessageLog.logMessage(
                "Logo not found", 'QgisShogunEditor', level=Qgis.Warning)

    def _handle_login(self):
        keycloak_url = self.dlg.get_keycloak_url()
        client_id = self.dlg.get_client_id()
        username = self.dlg.get_username()
        password = self.dlg.get_password()

        if not keycloak_url or not client_id:
            self.dlg.set_login_status("Bitte Keycloak URL und Client-ID eingeben", False)
            return

        if not username or not password:
            self.dlg.set_login_status("Bitte Benutzername und Passwort eingeben", False)
            return

        self._save_settings()

        self.keycloak_auth.configure(keycloak_url, client_id)
        self.dlg.set_login_status("Anmeldung läuft...", False)

        if self.keycloak_auth.login(username, password):
            self.dlg.clear_credentials()
            self.dlg.set_login_status("Angemeldet", True)
        else:
            self.dlg.set_login_status("Anmeldung fehlgeschlagen", False)

    def _on_login_success(self, token: str):
        self._initialize_graphql_client()
        self.dlg.set_login_status("Angemeldet", True)
        QgsMessageLog.logMessage(
            "Login successful", 'QgisShogunEditor', level=Qgis.Info)

    def _on_login_failed(self, error: str):
        self.dlg.set_login_status(f"Login fehlgeschlagen: {error}", False)
        QgsMessageLog.logMessage(
            f"Login failed: {error}", 'QgisShogunEditor', level=Qgis.Critical)

    def _handle_load(self):
        self._save_settings()
        self._initialize_graphql_client()
        self._load_applications()

    def _handle_cancel(self):
        self.dlg.reject()

    def _initialize_graphql_client(self):
        graphql_url = self.dlg.get_graphql_url()
        if not graphql_url:
            return

        sanitized_url = self._sanitize_url(graphql_url)
        self.graphql_client = GraphQLClient(sanitized_url, keycloak_auth=self.keycloak_auth)
        self.app_service = ApplicationService(self.graphql_client)
        self.layer_service = LayerService(self.graphql_client)

    def _sanitize_url(self, url: str) -> str:
        url = url.strip()
        if url.endswith('/graphql'):
            return url
        elif url.endswith('/'):
            return url + 'graphql'
        return url + '/graphql'

    def _load_applications(self):
        try:
            applications = self.app_service.get_all_applications()
            if applications:
                self.dlg.populate_applications_table(applications)
                self.dlg.switch_to_applications_tab()
            else:
                QgsMessageLog.logMessage(
                    "No applications found", 'QgisShogunEditor', level=Qgis.Warning)
        except Exception as e:
            QgsMessageLog.logMessage(
                f"Failed to load applications: {e}", 'QgisShogunEditor', level=Qgis.Critical)

    def _handle_table_double_click(self, item: QTableWidgetItem):
        app_id = self.dlg.get_selected_application_id()
        if app_id is None:
            return

        try:
            application = self.app_service.get_application_by_id(app_id)
            if application:
                self._load_application(application)
        except Exception as e:
            QgsMessageLog.logMessage(
                f"Failed to load application: {e}", 'QgisShogunEditor', level=Qgis.Critical)

    def _load_application(self, application: Application):
        QgsProject.instance().setTitle(application.name or "Unnamed Application")

        if application.client_config:
            self._apply_mapview(application)

        if application.layer_tree:
            self._load_layer_tree(application)

    def _apply_mapview(self, application: Application):
        qgis_project = QgsProject.instance()
        client_config = application.client_config

        if client_config and 'mapView' in client_config:
            map_view = client_config['mapView']
            projection = map_view.get('projection')

            if projection:
                crs = QgsCoordinateReferenceSystem(projection)
                qgis_project.setCrs(crs)

            center = map_view.get('center')
            if center:
                map_canvas = self.iface.mapCanvas()
                map_canvas.setCenter(QgsPointXY(center[0], center[1]))

            zoom = map_view.get('zoom')
            resolutions = map_view.get('resolutions')
            if resolutions and zoom is not None and zoom < len(resolutions):
                resolution = resolutions[zoom]
                dpi = 25.4 / 0.28
                map_canvas.zoomScale(resolution * dpi * 39.37)

    def _load_layer_tree(self, application: Application):
        root = QgsProject.instance().layerTreeRoot()
        root.clear()

        layer_ids = self._find_all_layer_ids(application.layer_tree)

        if layer_ids:
            layers_content = self.layer_service.get_layers_by_ids(layer_ids)
            self._build_layer_tree(application.layer_tree, layers_content, root)

    def _find_all_layer_ids(self, layer_tree: dict) -> list:
        layer_ids = []
        if "layerId" in layer_tree:
            layer_ids.append(layer_tree["layerId"])
        if "children" in layer_tree:
            for child in layer_tree["children"]:
                layer_ids.extend(self._find_all_layer_ids(child))
        return layer_ids

    def _build_layer_tree(self, tree_node: dict, layers_content: list, parent):
        new_group = parent
        if 'layerId' not in tree_node:
            title = tree_node.get('title', 'Group')
            new_group = parent.addGroup(title)

        if 'layerId' in tree_node:
            results = [layer for layer in layers_content
                       if layer.get_id() == tree_node['layerId']]
            if results:
                layer_data = results[0]
                if layer_data.source_config:
                    self._add_layer_to_tree(layer_data.source_config, parent)

        if 'children' in tree_node:
            for child in tree_node['children']:
                self._build_layer_tree(child, layers_content, new_group)

    def _add_layer_to_tree(self, layer_src_conf: dict, group):
        from qgis.core import QgsRasterLayer, QgsVectorLayer

        layer_names = layer_src_conf.get('layerNames', '')
        layer_url = layer_src_conf.get('url', '')

        if str(layer_url).startswith('/'):
            graphql_url = self.dlg.get_graphql_url()
            layer_url = graphql_url.rstrip('/graphql').rstrip('/') + layer_url

        layer_type = layer_src_conf.get('type', 'WMS').upper()

        if layer_type in ('WMS', 'TILEWMS'):
            layer = self._create_wms_layer(layer_names, layer_url, layer_src_conf)
        elif layer_type == 'WFS':
            layer = self._create_wfs_layer(layer_names, layer_url, layer_src_conf)
        else:
            QgsMessageLog.logMessage(
                f"Unsupported layer type: {layer_type}", 'QgisShogunEditor', level=Qgis.Warning)
            return

        if layer and layer.isValid():
            QgsProject.instance().addMapLayer(layer, False)
            group.addLayer(layer)
        elif layer is not None:
            QgsMessageLog.logMessage(
                f"Invalid layer: {layer_names}", 'QgisShogunEditor', level=Qgis.Warning)

    def _create_wms_layer(self, layer_names: str, layer_url: str, config: dict) -> QgsRasterLayer:
        params = {
            'layers': layer_names,
            'styles': '',
            'format': 'image/png',
            'crs': f'EPSG:{QgsProject.instance().crs().srsid()}',
            'url': layer_url,
            'tiled': 'true' if config.get('type', '').upper() == 'TILEWMS' else 'false'
        }

        if 'requestParams' in config:
            if 'TRANSPARENT' in config['requestParams']:
                params['transparent'] = 'true'

        uri = '&'.join([f"{k}={v}" for k, v in params.items()])
        return QgsRasterLayer(uri, layer_names, 'wms')

    def _create_wfs_layer(self, layer_names: str, layer_url: str, config: dict) -> QgsVectorLayer:
        params = {
            'service': 'WFS',
            'version': '2.0.0',
            'request': 'GetFeature',
            'typename': layer_names,
            'srsname': f'EPSG:{QgsProject.instance().crs().srsid()}'
        }
        uri = layer_url + '&'.join([f"{k}={v}" for k, v in params.items()])
        return QgsVectorLayer(uri, layer_names, 'WFS')

    def _open_project_link(self, event):
        if event.button() == Qt.LeftButton:
            QDesktopServices.openUrl(QUrl("https://www.terrestris.de/de/"))

    def get_keycloak_auth(self) -> KeycloakAuth:
        return self.keycloak_auth
